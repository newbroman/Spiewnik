-- ============================================================================
--  002_learning.sql — line progress (spaced review), vocab, study days.
--  Idempotent: safe to run more than once in the Supabase SQL editor.
--  Every table is owner-only under Row Level Security.
--
--  song_id is stored as TEXT so it works whatever type songs.id is
--  (uuid or bigint); the app always writes String(song.id). There is no FK to
--  songs for that reason, so rows for a deleted song are left behind; the app
--  ignores rows whose song no longer exists, and the cleanup trigger below
--  removes them when a song is deleted.
-- ============================================================================

-- ---- line_progress ------------------------------------------------------------
create table if not exists public.line_progress (
  user_id       uuid        not null default auth.uid() references auth.users on delete cascade,
  song_id       text        not null,
  line_idx      int         not null,
  line_text     text        not null default '',   -- the lyric line when graded; mismatch = stale
  state         text        not null check (state in ('known', 'shaky')),
  ease          real        not null default 2.5,
  interval_days real        not null default 0,
  due_at        timestamptz,
  reviews       int         not null default 0,
  updated_at    timestamptz not null default now(),
  primary key (user_id, song_id, line_idx)
);
create index if not exists line_progress_due_idx on public.line_progress (user_id, due_at);

alter table public.line_progress enable row level security;
drop policy if exists "line_progress owner select" on public.line_progress;
drop policy if exists "line_progress owner insert" on public.line_progress;
drop policy if exists "line_progress owner update" on public.line_progress;
drop policy if exists "line_progress owner delete" on public.line_progress;
create policy "line_progress owner select" on public.line_progress for select using (user_id = auth.uid());
create policy "line_progress owner insert" on public.line_progress for insert with check (user_id = auth.uid());
create policy "line_progress owner update" on public.line_progress for update using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "line_progress owner delete" on public.line_progress for delete using (user_id = auth.uid());

-- ---- vocab ----------------------------------------------------------------------
create table if not exists public.vocab (
  id         bigint generated by default as identity primary key,
  user_id    uuid        not null default auth.uid() references auth.users on delete cascade,
  word       text        not null,
  lemma      text        not null,
  gloss      text,
  note       text,
  pos        text,
  song_id    text,
  line       text,
  language   text        not null default '',
  created_at timestamptz not null default now(),
  unique (user_id, lemma, language)
);
create index if not exists vocab_user_song_idx on public.vocab (user_id, song_id);

alter table public.vocab enable row level security;

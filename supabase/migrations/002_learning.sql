-- ---- study_days (streaks) -------------------------------------------------------
create table if not exists public.study_days (
  user_id uuid not null default auth.uid() references auth.users on delete cascade,
  day     date not null,
  lines   int  not null default 0,
  primary key (user_id, day)
);

alter table public.study_days enable row level security;
drop policy if exists "study_days owner select" on public.study_days;
drop policy if exists "study_days owner insert" on public.study_days;
drop policy if exists "study_days owner update" on public.study_days;
drop policy if exists "study_days owner delete" on public.study_days;
create policy "study_days owner select" on public.study_days for select using (user_id = auth.uid());
create policy "study_days owner insert" on public.study_days for insert with check (user_id = auth.uid());
create policy "study_days owner update" on public.study_days for update using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "study_days owner delete" on public.study_days for delete using (user_id = auth.uid());

-- Atomic "+n lines today" for the signed-in user. The client passes its LOCAL
-- date so streaks follow the learner's own midnight. Runs as the caller
-- (security invoker), so RLS still applies.
create or replace function public.bump_study_day(p_day date, p_n int default 1)
returns int
language sql
security invoker
set search_path = public
as $$
  insert into public.study_days (user_id, day, lines)
  values (auth.uid(), p_day, greatest(p_n, 0))
  on conflict (user_id, day) do update set lines = public.study_days.lines + greatest(excluded.lines, 0)
  returning lines;
$$;
grant execute on function public.bump_study_day(date, int) to authenticated;

-- ---- tidy up when a song is deleted ---------------------------------------------
-- Line progress for a removed song is meaningless; vocab is kept (song_id is
-- just a back-link and the word is still useful).
create or replace function public.learning_song_deleted()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  delete from public.line_progress where user_id = old.user_id and song_id = old.id::text;
  return old;
end;
$$;

do $$
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'songs' and column_name = 'user_id') then
    execute 'drop trigger if exists learning_song_deleted on public.songs';
    execute 'create trigger learning_song_deleted after delete on public.songs
             for each row execute function public.learning_song_deleted()';
  end if;
end;
$$;
